"""Vendor the a4sx CLI's client scrub into ``src/a4sx/_cli_scrub.py``, and check that it has not drifted.

The a4sx CLI is one script, served at https://session-exchange.com/cli/a4sx.py. Before anything is uploaded
it applies the same scrub rules as the a4sx server: secrets, command-line passwords, Sheet ids, and personal
data, hosts, IP addresses and paths. This package must scrub exactly the same way, so it does not keep its
own rules. This script:

1. copies the CLI's client-scrub section (from ``# --- client scrub`` up to ``def summarize(``);
2. removes its comments and docstrings, which changes no behaviour (the commented original is the CLI);
3. rewrites the host rule's arguments, and renames one internal identifier. The CLI also redacts the
   subdomains of a host that is not part of this package; here the rule covers the subdomains of
   ``session-exchange.com`` only;
4. runs the CLI's own scrub and the vendored one on a corpus, in both modes, and fails unless every result is
   identical; then stores the CLI's results as parity vectors (``tests/vectors/scrub_parity.json``), which
   the test suite checks offline.

    python tools/vendor_scrub.py               # download the CLI, rewrite the module and the vectors
    python tools/vendor_scrub.py --cli PATH    # use a local copy of the CLI script instead
    python tools/vendor_scrub.py --check       # exit 1 if the module or the vectors are out of date

Stdlib only. Token-shaped corpus strings are assembled at runtime, so neither this file nor the vectors
file holds one.
"""

