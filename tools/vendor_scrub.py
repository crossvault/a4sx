# --- extraction and transformation ----------------------------------------------------------------------

def _region(cli: str) -> str:
    a = cli.index(START)
    b = cli.index(STOP, a)
    return cli[a:b + 1]


def _top_level_str(cli: str, name: str) -> str:
    for node in ast.parse(cli).body:
        if (isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name)
                and node.targets[0].id == name and isinstance(node.value, ast.Constant)):
            return str(node.value.value)
    raise SystemExit(f"the CLI has no top-level {name} string; update tools/vendor_scrub.py")


def _strip(region: str) -> str:
    """The region without comments and docstrings. Only whole lines that held nothing else are removed,
    so no string literal changes."""
    lines = region.splitlines(keepends=True)
    drop: set[int] = set()
    tree = ast.parse(region)
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)) and node.body:
            first = node.body[0]
            if isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant) \
                    and isinstance(first.value.value, str):
                rows = range(first.lineno - 1, first.end_lineno)
                if len(node.body) == 1:
                    indent = lines[first.lineno - 1][: first.col_offset]
                    lines[first.lineno - 1] = indent + "pass\n"
                    rows = range(first.lineno, first.end_lineno)
                drop.update(rows)
    cut: dict[int, int] = {}
    for tok in tokenize.generate_tokens(io.StringIO(region).readline):
        if tok.type == tokenize.COMMENT:
            row, col = tok.start[0] - 1, tok.start[1]
            if lines[row][:col].strip():
                cut[row] = col
            else:
                drop.add(row)
    out = []
    for i, line in enumerate(lines):
        if i in drop:
            continue
        if i in cut:
            line = line[: cut[i]].rstrip() + "\n"
        out.append(line)
    text = "".join(out)
    return re.sub(r"\n{4,}", "\n\n\n", text)  # only blank runs between statements; strings hold no such run


def vendor(cli: str) -> str:
    version = _top_level_str(cli, "__version__")
    public = _top_level_str(cli, "PUBLIC_DOMAIN")
    legacy = _top_level_str(cli, "LEGACY_PUBLIC_DOMAIN")
    if public != "session-exchange.com":
        raise SystemExit(f"the CLI's PUBLIC_DOMAIN is {public!r}; update tools/vendor_scrub.py")
    other_suffix = re.escape(legacy.split(".", 1)[1])          # the CLI's second host suffix
    body = _strip(_region(cli))
    edits = [
        # the default suffix of sr_extra_rules (callers always pass their own)
        (f'host_suffixes=r"{other_suffix}"', 'host_suffixes=r"session\\-exchange\\.com"'),
        # the CLI's call: allow the public host only, redact subdomains of the public domain only
        (f'(PUBLIC_DOMAIN, LEGACY_PUBLIC_DOMAIN), re.escape(PUBLIC_DOMAIN) + r"|{other_suffix}")',
         "(PUBLIC_DOMAIN,), re.escape(PUBLIC_DOMAIN))"),
    ]
    for old, new in edits:
        if body.count(old) != 1:
            raise SystemExit(f"expected exactly one {old!r} in the CLI's scrub section; update the tool")
        body = body.replace(old, new)
    # A neutral name for one internal identifier (behaviour-neutral: it is used only in this section).
    names = set(re.findall(r"^(_SR_[A-Z0-9_]+_B32) = _sr_re\.compile\(", body, re.M))
    if len(names) != 1 or "_SR_MINTED_B32" in body:
        raise SystemExit("expected one _SR_*_B32 token pattern in the CLI's scrub section; update the tool")
    body = re.sub(r"\b" + re.escape(names.pop()) + r"\b", "_SR_MINTED_B32", body)
    for word in (legacy, legacy.split(".", 1)[1], "LEGACY_PUBLIC_DOMAIN"):
        if word in body:
            raise SystemExit(f"{word!r} is still in the vendored scrub; update tools/vendor_scrub.py")
    sha = hashlib.sha256(cli.encode("utf-8")).hexdigest()[:16]
    return HEADER.format(version=version, sha=sha, url=CLI_URL) + body


def _load(code: str, extra: dict) -> dict:
    ns = {"bisect": bisect, "hashlib": hashlib, "json": json, "re": re, "uuid": uuid, **extra}
    exec(compile(code, "<scrub>", "exec"), ns)  # noqa: S102 - the CLI's own code, to compare against it
    return ns


def results(scrub_detail, cases) -> list[dict]:
    out = []
    for name, text in cases:
        row = {"name": name, "input": text}
        for mode in MODES:
            t, counts, hits = scrub_detail(text, mode)
            row[mode] = {"output": t, "counts": dict(sorted(counts.items())), "hits": hits}
        out.append(row)
    return out


def _split(s: str) -> str:
    """Break every run of 12+ word characters with JOIN, so the vectors file holds no token shape."""
    s = s.replace("PRIVATE KEY", "PRIV" + JOIN + "ATE KEY")
    return re.sub(r"[A-Za-z0-9_\-+/=.]{12,}", lambda m: JOIN.join(m.group(0)[i:i + 6]
                                                               for i in range(0, len(m.group(0)), 6)), s)


def vectors_json(rows: list[dict], version: str) -> str:
    doc = {"cli_version": version, "join": JOIN, "modes": list(MODES),
           "cases": [{**r, "input": _split(r["input"]),
                      **{m: {**r[m], "output": _split(r[m]["output"])} for m in MODES}} for r in rows]}
    return json.dumps(doc, ensure_ascii=True, indent=1, sort_keys=False) + "\n"


def build(cli: str) -> tuple[str, str]:
    module = vendor(cli)
    version = _top_level_str(cli, "__version__")
    region = _region(cli)
    original = _load("from __future__ import annotations\n" + region, {
        "PUBLIC_DOMAIN": _top_level_str(cli, "PUBLIC_DOMAIN"),
        "LEGACY_PUBLIC_DOMAIN": _top_level_str(cli, "LEGACY_PUBLIC_DOMAIN")})
    vendored = _load(module, {})
    cases = corpus()
    want, got = results(original["scrub_detail"], cases), results(vendored["scrub_detail"], cases)
    for w, g in zip(want, got):
        if w != g:
            raise SystemExit(f"parity broken on {w['name']!r}: the vendored scrub differs from the CLI's")
    fired = {rule for r in want for rule in r["full"]["counts"]}
    missing = sorted({name for name, _p in original["_SCRUB"]} - fired)
    if missing:
        raise SystemExit(f"the corpus never triggers these CLI rules: {', '.join(missing)}; extend corpus()")
    return module, vectors_json(want, version)


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--cli", help=f"a local copy of the CLI script (default: download {CLI_URL})")
    ap.add_argument("--check", action="store_true", help="exit 1 if the vendored files are out of date")
    a = ap.parse_args(argv)
    if a.cli:
        cli = Path(a.cli).read_text(encoding="utf-8")
    else:
        with urllib.request.urlopen(CLI_URL, timeout=60) as r:  # noqa: S310 - a fixed https URL
            cli = r.read().decode("utf-8")
    module, vectors = build(cli)
    if a.check:
        stale = [p for p, new in ((TARGET, module), (VECTORS, vectors))
                 if not p.exists() or p.read_text(encoding="utf-8") != new]
        for p in stale:
            print(f"{p.relative_to(REPO)} is out of date: run python tools/vendor_scrub.py")
        if not stale:
            print(f"vendored scrub matches the a4sx CLI {_top_level_str(cli, '__version__')}")
        return 1 if stale else 0
    TARGET.write_text(module, encoding="utf-8")
    VECTORS.parent.mkdir(parents=True, exist_ok=True)
    VECTORS.write_text(vectors, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(REPO)} and {VECTORS.relative_to(REPO)} from the a4sx CLI "
          f"{_top_level_str(cli, '__version__')}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
