def _a(*parts: str) -> str:
    return "".join(parts)


_ALNUM = "ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789"


def K(seed: str, n: int, alphabet: str = _ALNUM) -> str:
    """A deterministic synthetic value: ``n`` characters derived from ``seed``. Never a real credential."""
    out, i = [], 0
    while len(out) < n:
        for byte in hashlib.sha256(f"{seed}/{i}".encode()).digest():
            out.append(alphabet[byte % len(alphabet)])
        i += 1
    return "".join(out[:n])


